class DiseasePrediction(models.Model):
    id = models.AutoField(primary_key=True)

    # UUID generated by the client for offline-sync deduplication.
    client_uuid = models.UUIDField(
        default=uuid.uuid4,
        unique=True,
        editable=False
    )

    farm = models.ForeignKey(
        Farm,
        on_delete=models.CASCADE,
        related_name="disease_predictions"
    )

    sensor_reading = models.ForeignKey(
        SensorReading,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="disease_predictions"
    )

    treatment = models.ForeignKey(
        TreatmentRecommendation,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="predictions"
    )

    image = models.ImageField(
        upload_to="disease_images/%Y/%m/%d/"
    )

    predicted_label = models.CharField(
        max_length=100
    )

    confidence = models.FloatField()

    top_3_predictions = models.JSONField(
        null=True,
        blank=True
    )

    predicted_at = models.DateTimeField(
        auto_now_add=True,
        db_index=True
    )

    was_helpful = models.BooleanField(
        null=True,
        blank=True
    )

    class Meta:
        ordering = ["-predicted_at"]

    def __str__(self):
        return (
            f"{self.farm.name} - "
            f"{self.predicted_label} "
            f"({self.confidence:.2f})"
        )


class RiskScore(models.Model):

    RISK_BANDS = [
        ("low", "Low"),
        ("medium", "Medium"),
        ("high", "High"),
    ]

    id = models.AutoField(primary_key=True)

    farm = models.ForeignKey(
        Farm,
        on_delete=models.CASCADE,
        related_name="risk_scores"
    )

    treatment = models.ForeignKey(
        TreatmentRecommendation,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="risk_scores"
    )

    disease = models.CharField(
        max_length=100
    )

    score = models.FloatField()

    band = models.CharField(
        max_length=10,
        choices=RISK_BANDS
    )

    window_start = models.DateTimeField(
        null=True,
        blank=True
    )

    window_end = models.DateTimeField(
        null=True,
        blank=True
    )

    calculated_at = models.DateTimeField(
        auto_now_add=True,
        db_index=True
    )

    class Meta:
        ordering = ["-calculated_at"]

    def __str__(self):
        return (
            f"{self.farm.name} - "
            f"{self.disease}: "
            f"{self.score} ({self.band})"
        )
